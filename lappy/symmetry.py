"""lappy.symmetry -- symmetry-reduced Method of Particular Solutions.

Most benchmark domains (and most domains that show up in shape optimization)
have a nontrivial isometry group G. The Dirichlet spectrum then splits into
irreducible sectors, and MPS can be run one sector at a time. Three things
improve at once:

1. **Conditioning / resolution.** Each sector needs roughly ``|G|`` times
   fewer independent basis functions to reach the same resolution, so at a
   fixed cost the per-sector basis is far richer than the full-domain basis.

2. **Degeneracy separation.** Eigenvalues that are degenerate (or nearly so)
   in the full problem land in *different* sectors, where each is a simple,
   well-isolated minimum of its own tension curve. This is the single
   biggest accuracy win for domains like ``reg_ngon(8)``, whose full-domain
   tension curve has three eigenvalues inside a window of width 4e-3.

3. **Cost.** The GSVD is cubic in the basis size. Halving the column count
   is an 8x saving per sector, 4x overall for a two-element group.

Implementation note: rather than construct a reduced *geometry* with mixed
Dirichlet/Neumann conditions on the symmetry axes (fiddly, and it changes
the corner structure the basis builder sees), we symmetrize the *basis*:

    phi_j^chi(z) = sum_{g in G} chi(g) phi_j(g z)

Every ``phi_j^chi`` still solves the Helmholtz equation (the ``g`` are
isometries), and it lies in the ``chi``-isotypic subspace by construction.
Collocating it on the part of ``dOmega`` inside a fundamental domain is then
equivalent to the full problem restricted to that sector -- the symmetry
axes need no equations at all, since the projected functions satisfy the
right condition there identically.

The symmetrized family is rank-deficient by a factor ``|G|`` (phi_j and
phi_{g j} project to the same function up to sign). ``MPSEigensolver``'s
existing SVD regularization discards the dependent directions, so no
explicit column pruning is required for correctness; ``prune_columns``
does it anyway to recover the cubic cost saving.

Only real characters are supported, i.e. groups that are elementary abelian
2-groups (generated by commuting involutions: reflections and half-turns).
That covers every symmetric domain in the benchmark set.
"""
import numpy as np

from .bases import ParticularBasis
from .geometry import PointSet


# ---------------------------------------------------------------------------
# planar isometries
# ---------------------------------------------------------------------------

class Isometry:
    """A planar isometry ``z -> a*z + b`` (direct) or ``z -> a*conj(z) + b``
    (opposite), stored in complex form with ``|a| == 1``.

    ``half`` is a signed linear functional that is negated by the isometry
    (``half(g z) == -half(z)``); the closed half-plane ``half >= 0`` is a
    fundamental domain for the two-element group ``{e, g}``. It is ``None``
    for the identity.
    """

    def __init__(self, a, b, conj, name='g', half=None):
        self.a, self.b, self.conj, self.name = complex(a), complex(b), bool(conj), name
        self.half = half

    def __call__(self, z):
        z = np.asarray(z)
        return self.a * (np.conj(z) if self.conj else z) + self.b

    def grad_pullback(self, G):
        """Map an evaluated gradient ``G = f_x + i f_y`` at ``g(z)`` to the
        gradient of ``f o g`` at ``z``.

        Direct (``M = R_theta``): ``M^T = R_{-theta}``, i.e. multiply by
        ``conj(a)``. Opposite (``M = R_theta C``, ``C`` = conjugation):
        ``M^T = C R_{-theta}``, i.e. multiply by ``conj(a)`` then conjugate,
        which is ``a * conj(G)``.
        """
        return self.a * np.conj(G) if self.conj else np.conj(self.a) * G

    def __repr__(self):
        return f'Isometry({self.name})'


def identity():
    return Isometry(1.0, 0.0, False, name='e')


def reflection(p0, direction):
    """Reflection across the line through ``p0`` with complex ``direction``.

    ``z -> p0 + d^2 * conj(z - p0)`` where ``d = direction/|direction|``.
    """
    p0 = complex(p0)
    d = complex(direction)
    d /= abs(d)
    a = d * d
    b = p0 - a * np.conj(p0)

    def half(z):
        # signed distance to the line, positive on the left of `direction`
        return np.imag(np.conj(d) * (np.asarray(z) - p0))

    return Isometry(a, b, True, name=f'refl({p0:g},{d:g})', half=half)


def half_turn(center, direction=1.0):
    """Rotation by pi about ``center`` (``z -> 2c - z``).

    A fundamental domain is any half-plane whose boundary line passes
    through the center; ``direction`` selects which one (the cut line runs
    along ``direction``).
    """
    c = complex(center)
    d = complex(direction)
    d /= abs(d)

    def half(z):
        return np.imag(np.conj(d) * (np.asarray(z) - c))

    return Isometry(-1.0, 2 * c, False, name=f'rot180({c:g})', half=half)


# ---------------------------------------------------------------------------
# groups and sectors
# ---------------------------------------------------------------------------

class SymmetryGroup:
    """An elementary abelian 2-group of planar isometries, given by commuting
    involutive generators.

    ``sectors()`` enumerates the real characters as sign tuples; ``elements``
    holds ``(isometry, sign_exponents)`` for every group element, expanded as
    products over subsets of the generators.
    """

    def __init__(self, generators, name=''):
        self.generators = list(generators)
        self.name = name
        self._expand()

    def _expand(self):
        k = len(self.generators)
        elems = []
        for mask in range(2 ** k):
            g = identity()
            expo = []
            for i in range(k):
                bit = (mask >> i) & 1
                expo.append(bit)
                if bit:
                    g = _compose(self.generators[i], g)
            elems.append((g, tuple(expo)))
        self.elements = elems

    @property
    def order(self):
        return len(self.elements)

    def sectors(self):
        """All real characters, as tuples of +-1 (one entry per generator)."""
        k = len(self.generators)
        return [tuple(1 - 2 * ((m >> i) & 1) for i in range(k)) for m in range(2 ** k)]

    def character(self, sector, expo):
        chi = 1
        for s, e in zip(sector, expo):
            if e:
                chi *= s
        return chi

    def in_fundamental_domain(self, z, tol=0.0):
        """Boolean mask: points strictly inside the fundamental domain
        (intersection of the generators' positive half-planes)."""
        z = np.asarray(z)
        mask = np.ones(z.shape, dtype=bool)
        for g in self.generators:
            mask &= g.half(z) > tol
        return mask

    def __repr__(self):
        return f'SymmetryGroup({self.name or len(self.generators)} generators, order {self.order})'


def _compose(g1, g2):
    """``g1 o g2``, where ``g(z) = a * z^(c) + b`` and ``z^(c)`` means
    ``conj(z)`` when ``c`` is set."""
    a2, b2, c2 = g2.a, g2.b, g2.conj
    a1, b1, c1 = g1.a, g1.b, g1.conj
    if c1:
        a = a1 * np.conj(a2)
        b = a1 * np.conj(b2) + b1
    else:
        a = a1 * a2
        b = a1 * b2 + b1
    conj = c1 ^ c2
    return Isometry(a, b, conj, name=f'{g1.name}o{g2.name}')


