"""Render the suite as a markdown table plus a coverage matrix.

    python -m benchmarks.suite.report            # print to stdout
    python -m benchmarks.suite.report --write    # also write SUITE.md

Everything printed is derived from the geometry at run time, so ``SUITE.md`` is
a generated artifact: regenerate it rather than editing it.
"""
import argparse
import os
import sys

from .domains import CORE, SUITE, TIERS, validate
from .features import GEOMETRIC_TAGS, SPECTRAL_TAGS, TAGS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'SUITE.md')

MIN_PER_TAG = 2


def _fmt_p(f):
    if not f['n_corners']:
        return '--'
    lo, hi = f['min_p'], f['max_p']
    return f'{lo:.3g}' if abs(hi - lo) < 1e-12 else f'{lo:.3g}-{hi:.3g}'


def table(keys=None):
    keys = keys or list(SUITE)
    lines = [
        '| key | tier | corners (reg/sing/reent/sharp) | p | slend | curv disc | '
        'symmetry | truth | status | digits |',
        '|---|---|---|---|---|---|---|---|---|---|',
    ]
    for tier in TIERS:
        for key in keys:
            d = SUITE[key]
            if d.tier != tier:
                continue
            f = d.features()
            sym = f['sym_name'] or ('none' if not d.symmetric else 'UNREGISTERED')
            dig = f'{d.digit_ceiling:.1f}' if d.digit_ceiling else '--'
            lines.append(
                f"| `{key}` | {d.tier} | "
                f"{f['n_corners']} ({f['n_regular']}/{f['n_singular']}/"
                f"{f['n_reentrant']}/{f['n_sharp']}) | {_fmt_p(f)} | "
                f"{f['slenderness']:.2f} | {f['n_curvature_discont']} | "
                f"{sym} | {d.truth} | {d.status} | {dig} |")
    return lines


def coverage():
    counts = {t: [] for t in sorted(TAGS)}
    for key, d in SUITE.items():
        for t in d.tags:
            counts[t].append(key)

    lines = ['| tag | kind | n | domains |', '|---|---|---|---|']
    thin = []
    for t, keys in counts.items():
        kind = 'geometric' if t in GEOMETRIC_TAGS else 'spectral'
        mark = '' if len(keys) >= MIN_PER_TAG else ' **<-- thin**'
        if len(keys) < MIN_PER_TAG:
            thin.append(t)
        shown = ', '.join(f'`{k}`' for k in keys) or '_none_'
        lines.append(f'| {t} | {kind} | {len(keys)}{mark} | {shown} |')
    return lines, thin


def symmetry_gaps():
    """Domains with a real symmetry that ``lappy.symmetry`` cannot supply."""
    out = []
    for key, d in SUITE.items():
        if d.symmetric and d.group() is None:
            out.append((key, d.family))
    return out


def render():
    parts = []
    parts.append('# Benchmark domain suite')
    parts.append('')
    parts.append('_Generated by `python -m benchmarks.suite.report --write`. '
                 'Do not edit; edit `domains.py` and regenerate._')
    parts.append('')
    parts.append(f'{len(SUITE)} domains. Columns: corner counts are '
                 '`total (regular/singular/reentrant/sharp)`; `p` is the range '
                 'of corner exponents `pi/gamma`; `slend` is '
                 '`diameter / (2 * inradius)` (1.0 for a disk); `digits` is the '
                 'best accuracy observed to date.')
    parts.append('')
    parts.append('## Domains')
    parts.append('')
    parts += table()

    parts.append('')
    parts.append('## Rationale')
    parts.append('')
    for tier in TIERS:
        parts.append(f'### tier: {tier}')
        parts.append('')
        for key, d in SUITE.items():
            if d.tier == tier:
                parts.append(f'- **`{key}`** -- {d.why}.')
        parts.append('')

    parts.append('## Tag coverage')
    parts.append('')
    cov, thin = coverage()
    parts += cov
    parts.append('')
    if thin:
        parts.append(f'Thinly covered (< {MIN_PER_TAG} domains): '
                     + ', '.join(f'`{t}`' for t in thin) + '.')
    else:
        parts.append(f'Every tag has at least {MIN_PER_TAG} representatives.')

    gaps = symmetry_gaps()
    parts.append('')
    parts.append('## Symmetry gaps')
    parts.append('')
    if gaps:
        parts.append('These domains have an obvious symmetry group that '
                     '`lappy.symmetry.domain_symmetry` does not know about, so '
                     'they cannot currently use the symmetry-reduced solve. '
                     'This is a concrete to-do list for `lappy/symmetry.py`:')
        parts.append('')
        for key, fam in gaps:
            parts.append(f'- `{key}` (family `{fam}`)')
    else:
        parts.append('None: every symmetric domain has a registered group.')

    parts.append('')
    parts.append('## Core subset')
    parts.append('')
    parts.append('One representative per mechanism, for spot checks when the '
                 'full suite is too expensive:')
    parts.append('')
    parts += table(list(CORE))
    parts.append('')
    return '\n'.join(parts)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--write', action='store_true',
                    help=f'write {os.path.relpath(OUT)} as well as printing')
    args = ap.parse_args(argv)

    problems = validate()
    if problems:
        print('REGISTRY PROBLEMS:', file=sys.stderr)
        for p in problems:
            print(f'  - {p}', file=sys.stderr)
        return 1

    text = render()
    print(text)
    if args.write:
        with open(OUT, 'w') as fh:
            fh.write(text + '\n')
        print(f'\nwrote {OUT}', file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
